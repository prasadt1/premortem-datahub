#!/usr/bin/env python3
"""Generate docs/eval-explorer-data.{json,js} from the frozen eval (binder-only).

Loads corpus / labels / schema the same way as eval/run_eval.py, runs
classify_query with subject_table + tables for each case, and writes the
explorer payload. Never hand-author the JSON — regenerate via this script.

Usage:
  python tools/generate_eval_explorer.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVAL_DIR = ROOT / "eval"
DOCS_DIR = ROOT / "docs"

sys.path.insert(0, str(ROOT / "src"))

from premortem.classify import classify_query  # noqa: E402


def load_fixture():
    """Mirror eval/run_eval.py::load_fixture."""
    schema = json.loads((EVAL_DIR / "schema.json").read_text())
    labels = json.loads((EVAL_DIR / "labels.json").read_text())
    cases = []
    for case in labels["cases"]:
        sql = (EVAL_DIR / "corpus" / f"{case['id']}.sql").read_text()
        cases.append({**case, "sql": sql})
    return schema, labels, cases


def main() -> None:
    schema, _labels, cases = load_fixture()
    column = schema["subject"]["column"]
    dialect = schema["subject"].get("dialect", "snowflake")
    subject = schema["subject"]["dataset"]
    tables = schema["tables"]

    rows = []
    n_agree = 0
    for c in cases:
        result = classify_query(
            c["sql"],
            column=column,
            dialect=dialect,
            subject_table=subject,
            tables=tables,
        )
        predicted = result.severity.value
        agree = predicted == c["gold"]
        if agree:
            n_agree += 1
        row = {
            "id": c["id"],
            "stratum": c["stratum"],
            "sql": c["sql"],
            "gold": c["gold"],
            "predicted": predicted,
            "agree": agree,
            "evidence": result.evidence,
            "unknown_reason": result.unknown_reason,
        }
        # Binder-only has no agent_note; include only when present (future hooks).
        agent_note = getattr(result, "agent_note", None)
        if agent_note:
            row["agent_note"] = agent_note
        rows.append(row)

    payload = {
        "source": "frozen eval (binder-only classifier)",
        "column": column,
        "subject_table": subject,
        "dialect": dialect,
        "n_cases": len(rows),
        "n_agree": n_agree,
        "n_disagree": len(rows) - n_agree,
        "cases": rows,
    }

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    json_path = DOCS_DIR / "eval-explorer-data.json"
    js_path = DOCS_DIR / "eval-explorer-data.js"
    json_path.write_text(json.dumps(payload, indent=2) + "\n")
    js_path.write_text(
        "/* Generated by tools/generate_eval_explorer.py — do not hand-edit. */\n"
        "window.EVAL_EXPLORER_DATA = "
        + json.dumps(payload, indent=2)
        + ";\n"
    )

    print(
        f"Wrote {len(rows)} cases → {json_path.relative_to(ROOT)} "
        f"({n_agree} agree / {len(rows) - n_agree} disagree)"
    )


if __name__ == "__main__":
    main()
